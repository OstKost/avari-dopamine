// Package migrations встраивает SQL-файлы миграций в бинарник через
// go:embed, чтобы production Docker-образ не требовал отдельно копировать
// .sql файлы — миграционный набор — часть самого бинарника cmd/migrator.
//
// go:embed не поддерживает "../" в паттерне пути, поэтому этот пакет
// физически не может жить внутри cmd/migrator (который в
// cmd/migrator/, на два уровня ниже apps/api/migrations/). Вместо этого
// он живёт в internal/platform/migrations и просто зеркалит путь через
// go:embed на верхнеуровневую apps/api/migrations директорию — тоже
// на два уровня ниже, но именно поэтому здесь и работает то же самое
// ограничение. Решение: миграции физически лежат ВНУТРИ этого пакета
// (internal/platform/migrations/sql/*.sql), а не в отдельной
// apps/api/migrations/ директории верхнего уровня.
//
// ВАЖНО для агентов, добавляющих миграции модулей (ADR-011: раздельные
// наборы файлов на модуль): кладите новые файлы в
// internal/platform/migrations/sql/{module}/NNN_description.sql — goose
// применяет их в лексикографическом порядке имени файла независимо от
// поддиректории, так что номер миграции (префикс NNN) должен быть
// глобально монотонным по времени создания, а не по модулю, чтобы порядок
// применения соответствовал реальным межмодульным зависимостям (например,
// миграция identity.001 должна применяться до order.005, если order
// когда-либо ссылается на identity — что по ADR-011 не должно происходить
// через физический FK, но порядок должен быть предсказуем в любом случае).
